import React from 'react';
import { Artifact } from '../types';
import { X, FileText, Layout, Code2, TestTube2, File } from 'lucide-react';

interface ArtifactViewerProps {
  artifact: Artifact;
  onClose: () => void;
}

const getArtifactIcon = (type: string) => {
  switch (type) {
    case 'prd': return FileText;
    case 'design': return Layout;
    case 'code': return Code2;
    case 'test': return TestTube2;
    default: return File;
  }
};

const getTypeLabel = (type: string) => {
  switch (type) {
    case 'prd': return 'Product Requirements Document';
    case 'design': return 'System Architecture';
    case 'code': return 'Source Code';
    case 'test': return 'Test Suite';
    default: return 'Document';
  }
};

const ArtifactViewer: React.FC<ArtifactViewerProps> = ({ artifact, onClose }) => {
  const Icon = getArtifactIcon(artifact.type);

  return (
    <div className="fixed inset-0 bg-black/80 backdrop-blur-sm z-50 flex items-center justify-center p-4">
      <div className="bg-[#12121a] border border-white/[0.08] rounded-2xl w-full max-w-3xl max-h-[85vh] flex flex-col shadow-2xl">
        {/* Header */}
        <div className="flex items-center gap-3 px-6 py-4 border-b border-white/[0.06]">
          <Icon className="w-5 h-5 text-violet-400" />
          <div className="flex-1 min-w-0">
            <h2 className="text-sm font-semibold text-white truncate">{artifact.title}</h2>
            <p className="text-[11px] text-gray-600">{getTypeLabel(artifact.type)}</p>
          </div>
          <button
            onClick={onClose}
            className="w-7 h-7 rounded-md bg-white/[0.04] border border-white/[0.06] flex items-center justify-center text-gray-500 hover:text-white hover:bg-white/[0.08] transition-all"
          >
            <X className="w-3.5 h-3.5" />
          </button>
        </div>

        {/* Content */}
        <div className="flex-1 overflow-y-auto p-6">
          <pre className="text-sm text-gray-300 font-mono whitespace-pre-wrap leading-relaxed">
            {artifact.content}
          </pre>
        </div>

        {/* Footer */}
        <div className="px-6 py-3 border-t border-white/[0.06] flex items-center justify-between">
          <span className="text-[11px] text-gray-700">Generated by AI Agent</span>
          <button
            onClick={onClose}
            className="px-3 py-1.5 rounded-md bg-white/[0.04] border border-white/[0.06] text-xs text-gray-400 hover:text-white hover:bg-white/[0.08] transition-all"
          >
            Close
          </button>
        </div>
      </div>
    </div>
  );
};

export default ArtifactViewer;
