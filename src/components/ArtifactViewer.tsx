import React from 'react';
import { Artifact } from '../types';

interface ArtifactViewerProps {
  artifact: Artifact;
  onClose: () => void;
}

const ArtifactViewer: React.FC<ArtifactViewerProps> = ({ artifact, onClose }) => {
  const getTypeIcon = () => {
    switch (artifact.type) {
      case 'prd': return '📋';
      case 'design': return '🏗️';
      case 'code': return '💻';
      case 'test': return '🧪';
      default: return '📄';
    }
  };

  const getTypeLabel = () => {
    switch (artifact.type) {
      case 'prd': return 'Product Requirements Document';
      case 'design': return 'System Architecture';
      case 'code': return 'Source Code';
      case 'test': return 'Test Suite';
      default: return 'Document';
    }
  };

  return (
    <div className="fixed inset-0 bg-black/70 backdrop-blur-sm z-50 flex items-center justify-center p-4 animate-fadeIn">
      <div className="bg-gray-900 border border-gray-700 rounded-2xl w-full max-w-3xl max-h-[85vh] flex flex-col shadow-2xl">
        {/* Header */}
        <div className="flex items-center gap-3 px-6 py-4 border-b border-gray-700/50">
          <span className="text-2xl">{getTypeIcon()}</span>
          <div className="flex-1">
            <h2 className="text-lg font-bold text-white">{artifact.title}</h2>
            <p className="text-xs text-gray-500">{getTypeLabel()}</p>
          </div>
          <button
            onClick={onClose}
            className="w-8 h-8 rounded-lg bg-gray-800 border border-gray-700 flex items-center justify-center text-gray-400 hover:text-white hover:border-gray-600 transition-colors"
          >
            ✕
          </button>
        </div>

        {/* Content */}
        <div className="flex-1 overflow-y-auto p-6">
          <pre className="text-sm text-gray-300 font-mono whitespace-pre-wrap leading-relaxed">
            {artifact.content}
          </pre>
        </div>

        {/* Footer */}
        <div className="px-6 py-3 border-t border-gray-700/50 flex items-center justify-between">
          <div className="flex items-center gap-2">
            <div className="w-2 h-2 bg-green-500 rounded-full" />
            <span className="text-xs text-gray-500">Generated by MetaGPT Agent</span>
          </div>
          <button
            onClick={onClose}
            className="px-4 py-1.5 rounded-lg bg-gray-800 border border-gray-700 text-xs text-gray-400 hover:text-white hover:border-gray-600 transition-colors"
          >
            Close
          </button>
        </div>
      </div>
    </div>
  );
};

export default ArtifactViewer;
